/**
 * Exports the catalogs the CODE depends on into a seed migration.
 *
 * The schema baseline gets a fresh database to the right shape and no further. Some tables are not
 * customer data but a contract with the source tree: scripts/check-feature-keys.mjs exists purely
 * because a feature key named in TypeScript and a row in `features` must agree, and it fails on an
 * empty table. Those catalogs belong in version control for the same reason the feature keys do.
 *
 * Deliberately narrow. Only tables on the allowlist below are exported, and every one of them is
 * platform reference data with no tenant column. Plans, prices and coupons are NOT here: they are
 * commercial decisions that legitimately differ between a developer's database and production, and
 * they are created through the admin UI.
 *
 * Read with the service role key because these tables are RLS-enabled with no policy and no grant
 * to tenant_app — invisible to the app's own connection by design.
 *
 *   node --env-file=.env.local scripts/dump-reference-data.mjs
 */
import { createClient } from "@supabase/supabase-js";
import { writeFileSync } from "node:fs";
import process from "node:process";

const OUT = "supabase/migrations/0016_reference_data.sql";

/** table -> columns that identify a row for the ON CONFLICT clause. */
const TABLES = [
  ["feature_modules", ["key"]],
  ["features", ["key"]],
  ["meters", ["key"]],
  ["payment_providers", ["code"]],
];

const url = process.env.NEXT_PUBLIC_SUPABASE_URL;
const key = process.env.SUPABASE_SERVICE_ROLE_KEY;
if (!url || !key) {
  console.error("NEXT_PUBLIC_SUPABASE_URL and SUPABASE_SERVICE_ROLE_KEY are required.");
  process.exit(1);
}
const db = createClient(url, key, { auth: { persistSession: false } });

function literal(v) {
  if (v === null || v === undefined) return "null";
  if (typeof v === "number") return String(v);
  if (typeof v === "boolean") return v ? "true" : "false";
  if (Array.isArray(v) || typeof v === "object") {
    return `'${JSON.stringify(v).replace(/'/g, "''")}'::jsonb`;
  }
  return `'${String(v).replace(/'/g, "''")}'`;
}

const out = [];
const say = (s = "") => out.push(s);

say("-- Platform reference data.");
say("--");
say("-- GENERATED by scripts/dump-reference-data.mjs. These four catalogs are a contract with the");
say("-- source tree rather than customer data: check-feature-keys.mjs asserts that every feature key");
say("-- named in TypeScript has a row here, so an empty table is a failing build, not an empty screen.");
say("--");
say("-- Upserts rather than inserts, so re-running never fights an existing database. Timestamps and");
say("-- anything server-generated are left out and left to their defaults.");
say("");

let total = 0;
for (const [table, conflict] of TABLES) {
  const { data, error } = await db.from(table).select("*");
  if (error) {
    console.error(`${table}: ${error.message}`);
    say(`-- ${table}: could not be read (${error.message})`);
    continue;
  }
  if (!data.length) {
    say(`-- ${table}: no rows`);
    continue;
  }

  // Drop columns the database fills in itself; carrying them makes the diff noisy on every dump.
  const VOLATILE = new Set(["created_at", "updated_at", "updated_by", "created_by"]);
  const cols = Object.keys(data[0]).filter((c) => !VOLATILE.has(c));

  say(`-- ${table} (${data.length} rows)`);
  say(`insert into public.${table} (${cols.join(", ")}) values`);
  say(data.map((row) => `  (${cols.map((c) => literal(row[c])).join(", ")})`).join(",\n"));
  say(`on conflict (${conflict.join(", ")}) do update set`);
  say(
    cols
      .filter((c) => !conflict.includes(c))
      .map((c) => `  ${c} = excluded.${c}`)
      .join(",\n"),
  );
  say(";");
  say("");
  total += data.length;
  console.log(`${table}: ${data.length} rows`);
}

writeFileSync(OUT, out.join("\n"), "utf8");
console.log(`wrote ${OUT} (${total} rows)`);
