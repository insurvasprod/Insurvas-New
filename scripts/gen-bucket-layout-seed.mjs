// Writes supabase/migrations/20261009110000_la_4_bucket_layouts.sql from scripts/la4-bucket-layouts.mjs,
// so the seeded layouts are exactly the ones lib/ingestion/bucketLayouts.test.mjs reads the samples
// with. Run: node scripts/gen-bucket-layout-seed.mjs
import { writeFileSync } from "node:fs";

import { ASSIGNMENTS, LAYOUTS, entriesOf, pdfOf } from "./la4-bucket-layouts.mjs";

const q = (value) => (value === null || value === undefined ? "null" : `'${String(value).replaceAll("'", "''")}'`);
const json = (value) => (value === null || value === undefined ? "null" : `${q(JSON.stringify(value))}::jsonb`);

const lines = [];
lines.push(`-- LA-4 bucket door, round 2 (2026-10-09) · the platform layouts for the bucket samples' carriers,
-- and PDF layouts. GENERATED by scripts/gen-bucket-layout-seed.mjs from scripts/la4-bucket-layouts.mjs
-- — edit those and regenerate, never this file by hand. lib/ingestion/bucketLayouts.test.mjs reads
-- every sample file (docs/la4/bucket-samples) with these exact layouts against the answer key.
--
--   1. carrier_layout_map.pdf_layout: how a carrier's PDF statement is cut into columns (each column's
--      left edge, which column starts a row, an optional second line, where the table starts and
--      stops). A PDF waits for one, like a spreadsheet waits for its layout map.
--   2. Two transforms: mmddyy (8/6/26, 061426) and fraction_to_bp (0.825 is 82.5%).
--   3. ${LAYOUTS.length} platform layouts, seeded IN REVIEW: staff publish each in Admin › Layout maps after
--      reading it. Until then the carriers' files wait for a layout, as today.
--   4. ${ASSIGNMENTS.length} platform assignments (carrier + file type → layout). An agency's own assignment still wins.
--
-- Rollback: delete the in-review maps by layout_key (their entries cascade) and the platform
-- assignments below; the column and the transforms can stay.

alter table public.carrier_layout_map add column if not exists pdf_layout jsonb;
alter table public.carrier_layout_map drop constraint if exists carrier_layout_map_pdf_layout;
alter table public.carrier_layout_map add constraint carrier_layout_map_pdf_layout
  check (pdf_layout is null or (jsonb_typeof(pdf_layout) = 'object' and jsonb_typeof(pdf_layout -> 'columns') = 'array' and pdf_layout ? 'rowStart'));

alter table public.carrier_layout_map_entry drop constraint if exists carrier_layout_map_entry_transform;
alter table public.carrier_layout_map_entry add constraint carrier_layout_map_entry_transform
  check (transform in ('none', 'strip_currency', 'mmddyyyy', 'mmddyy', 'yyyymmdd', 'digits_only', 'negate', 'pct_to_bp', 'fraction_to_bp'));

-- A published map is frozen, its PDF layout included (the guard lists what it freezes).
create or replace function public.carrier_layout_map_guard()
returns trigger
language plpgsql
set search_path = public, pg_temp
as $guard$
declare
  v_type text;
begin
  if tg_op = 'INSERT' then
    if new.status in ('published', 'retired') then
      raise exception 'A layout map is published from a draft, never inserted published.' using errcode = 'P0001';
    end if;
    select file_type into v_type from public.carrier_layout_map
     where layout_key = new.layout_key and coalesce(tenant_id, '00000000-0000-0000-0000-000000000000'::uuid) = coalesce(new.tenant_id, '00000000-0000-0000-0000-000000000000'::uuid)
     limit 1;
    if v_type is not null and v_type <> new.file_type then
      raise exception 'Every version of layout % reads % files.', new.layout_key, v_type using errcode = 'P0001';
    end if;
    return new;
  end if;
  if tg_op = 'DELETE' then
    if old.status in ('published', 'retired') then
      raise exception 'A published layout map is never deleted; retire it.' using errcode = 'P0001';
    end if;
    return old;
  end if;
  if old.status in ('published', 'retired') then
    if new.tenant_id is distinct from old.tenant_id or new.layout_key is distinct from old.layout_key
       or new.name is distinct from old.name or new.file_type is distinct from old.file_type
       or new.version is distinct from old.version or new.header_row_index is distinct from old.header_row_index
       or new.sheet_name is distinct from old.sheet_name or new.row_count_swing_pct is distinct from old.row_count_swing_pct
       or new.total_row_column is distinct from old.total_row_column or new.total_row_value is distinct from old.total_row_value
       or new.pdf_layout is distinct from old.pdf_layout
       or new.proposal_source is distinct from old.proposal_source or new.created_by is distinct from old.created_by
       or new.created_by_admin is distinct from old.created_by_admin or new.approved_by is distinct from old.approved_by
       or new.approved_by_admin is distinct from old.approved_by_admin or new.approved_at is distinct from old.approved_at then
      raise exception 'A published layout map cannot be edited; start version % instead.', old.version + 1 using errcode = 'P0001';
    end if;
    if new.status is distinct from old.status and not (old.status = 'published' and new.status = 'retired') then
      raise exception 'A published layout map can only be retired.' using errcode = 'P0001';
    end if;
  end if;
  new.updated_at := now();
  return new;
end;
$guard$;
do $$
declare
  v_map uuid;
begin`);

for (const layout of LAYOUTS) {
  lines.push(`
  -- ${layout.name}
  select id into v_map from public.carrier_layout_map where tenant_id is null and layout_key = ${q(layout.key)} and version = 1;
  if v_map is null then
    insert into public.carrier_layout_map (tenant_id, layout_key, name, file_type, version, status, header_row_index, sheet_name, pdf_layout, proposal_source)
    values (null, ${q(layout.key)}, ${q(layout.name)}, ${q(layout.fileType)}, 1, 'in_review', ${layout.headerRow}, ${q(layout.sheet)}, ${json(pdfOf(layout))}, 'manual')
    returning id into v_map;
    insert into public.carrier_layout_map_entry (map_id, source_column, target_field, data_type, transform, required, sort_order, enum_values) values`);
  const entries = entriesOf(layout);
  lines.push(entries.map((entry, index) => `      (v_map, ${q(entry.sourceColumn)}, ${q(entry.targetField)}, ${q(entry.dataType)}, ${q(entry.transform)}, ${entry.required}, ${index + 1}, ${json(entry.enumValues)})`).join(",\n") + ";");
  lines.push(`  end if;`);
}

lines.push(`
  -- Which carrier's files each layout reads (platform; an agency's own assignment still wins).`);
for (const [code, fileType, key] of ASSIGNMENTS) {
  lines.push(`  insert into public.carrier_layout_assignment (tenant_id, carrier_id, file_type, layout_key)
  select null, c.id, ${q(fileType)}, ${q(key)} from public.carriers c
   where c.code = ${q(code)} and c.organization_id is null
     and not exists (select 1 from public.carrier_layout_assignment a where a.tenant_id is null and a.carrier_id = c.id and a.file_type = ${q(fileType)});`);
}
lines.push(`end $$;

-- ─── self-check ────────────────────────────────────────────────────────────────────────────────
do $$
begin
  if (select count(*) from public.carrier_layout_map where tenant_id is null and layout_key in (${LAYOUTS.map((layout) => q(layout.key)).join(", ")})) <> ${LAYOUTS.length} then
    raise exception '20261009110000: not every layout was seeded';
  end if;
  if position('new.pdf_layout is distinct from old.pdf_layout' in pg_get_functiondef('public.carrier_layout_map_guard()'::regprocedure)) = 0 then
    raise exception '20261009110000: a published map''s PDF layout is not frozen';
  end if;
  if (select count(*) from public.carrier_layout_map where tenant_id is null and pdf_layout is not null and layout_key in (${LAYOUTS.filter((layout) => layout.pdf).map((layout) => q(layout.key)).join(", ")})) <> ${LAYOUTS.filter((layout) => layout.pdf).length} then
    raise exception '20261009110000: a PDF layout is missing';
  end if;
  if (select count(*) from public.carrier_layout_map_entry e join public.carrier_layout_map m on m.id = e.map_id where m.tenant_id is null and m.layout_key in (${LAYOUTS.map((layout) => q(layout.key)).join(", ")})) <> ${LAYOUTS.reduce((sum, layout) => sum + layout.entries.length, 0)} then
    raise exception '20261009110000: the layouts do not have all their columns';
  end if;
  if (select count(*) from public.carrier_layout_assignment a join public.carriers c on c.id = a.carrier_id where a.tenant_id is null and c.organization_id is null and c.code in (${[...new Set(ASSIGNMENTS.map(([code]) => code))].map(q).join(", ")})) < ${ASSIGNMENTS.length} then
    raise exception '20261009110000: not every carrier has its layouts assigned';
  end if;
end $$;
`);

writeFileSync(new URL("../supabase/migrations/20261009110000_la_4_bucket_layouts.sql", import.meta.url), lines.join("\n"));
console.log(`wrote ${LAYOUTS.length} layouts, ${ASSIGNMENTS.length} assignments`);
