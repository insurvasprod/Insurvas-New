/** k.spark: a 2px line over a 12% area, a 3px dot on the last point. Flat when every value is the same. */
export function Spark({ values, width = 110, height = 44, gold }: { values: number[]; width?: number; height?: number; gold?: boolean }) {
  const p = usePalette();
  if (values.length < 2) return <View style={{ width, height }} />;
  const max = Math.max(...values);
  const min = Math.min(...values);
  const sx = width / (values.length - 1);
  const sy = (height - 6) / (max - min || 1);
  const pts = values.map((v, i) => [i * sx, height - 3 - (v - min) * sy] as const);
  const d = pts.map((pt, i) => `${i ? "L" : "M"}${pt[0].toFixed(1)} ${pt[1].toFixed(1)}`).join(" ");
  const col = gold ? p.gold : p.green;
  const last = pts[pts.length - 1];
  return (
    <Svg width={width} height={height} accessibilityElementsHidden importantForAccessibility="no-hide-descendants">
      <Path d={`${d} L${width} ${height} L0 ${height}Z`} fill={col} opacity={0.12} />
      <Path d={d} fill="none" stroke={col} strokeWidth={2} strokeLinejoin="round" strokeLinecap="round" />
      <Circle cx={last[0]} cy={last[1]} r={3} fill={col} />
    </Svg>
  );
}

/** k.bars: bars 6px apart on one scale, the highlighted one solid and the rest at 38%, labels 10px muted. */
export function Bars({ values, labels, height = 100, width = 330, highlight }: { values: number[]; labels?: string[]; height?: number; width?: number; highlight?: number }) {
  const p = usePalette();
  const hasLabels = Boolean(labels?.some(Boolean));
  const padB = hasLabels ? 18 : 2;
  const ih = height - padB - 4;
  const n = Math.max(1, values.length);
  const gap = 6;
  const bw = (width - gap * (n - 1)) / n;
  const max = Math.max(...values, 0) || 1;
  return (
    <Svg width="100%" height={height} viewBox={`0 0 ${width} ${height}`} accessibilityElementsHidden importantForAccessibility="no-hide-descendants">
      {values.map((v, i) => {
        const h = Math.max(2, (v / max) * ih);
        const x = i * (bw + gap);
        return <Rect key={i} x={x} y={4 + ih - h} width={bw} height={h} rx={3} fill={p.green} opacity={i === highlight ? 1 : 0.38} />;
      })}
      {hasLabels ? labels!.map((l, i) => (l ? <SvgText key={`l${i}`} x={i * (bw + gap) + bw / 2} y={height - 3} textAnchor="middle" fontSize={10} fill={p.muted} fontFamily={F.r}>{l}</SvgText> : null)) : null}
    </Svg>
  );
}

/** .prog: a 6px (or `height`) track with the filled share in green, or gold. */
export function Progress({ pct, gold, height = 6, style }: { pct: number; gold?: boolean; height?: number; style?: ViewStyle }) {
  const p = usePalette();
  const share = Math.max(0, Math.min(100, pct));
  return (
    <View style={[{ height, borderRadius: height / 2, backgroundColor: p.track, overflow: "hidden" }, style]}>
      <View style={{ width: `${share}%`, height: "100%", borderRadius: height / 2, backgroundColor: gold ? p.gold : p.green }} />
    </View>
  );
}

/** .tiles: two to a row, 10px apart, inside the 16px gutter. */
export function TileGrid({ children }: { children: ReactNode }) {
  const items = Children.toArray(children).filter(Boolean);
  return (
    <View style={{ flexDirection: "row", flexWrap: "wrap", gap: 10, paddingHorizontal: 16 }}>
      {items.map((child, i) => <View key={i} style={{ flexBasis: "47%", flexGrow: 1 }}>{child}</View>)}
    </View>
  );
}

/** "↑ 18 vs October": the change in gold (a rise is gold, owner rule), its comparison named in muted words. */
export function ChangeLine({ arrow, value, against, note }: { arrow: "↑" | "↓" | null; value: string; against: string; note?: string }) {
  const p = usePalette();
  return (
    <Text style={{ fontFamily: F.r, fontSize: 12.5, color: p.muted }}>
      {arrow ? <Text style={{ fontFamily: F.s, color: p.goldInk }}>{`${arrow} ${value}`}</Text> : <Text>{"Same as"}</Text>}
      {` ${arrow ? "vs " : ""}${against}${note ? `, ${note}` : ""}`}
    </Text>
  );
}

