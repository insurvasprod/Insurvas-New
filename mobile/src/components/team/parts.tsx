/** A check line (board I5): a 20px tick or cross, the list's name, and what it found in muted words. */
export function CheckLine({ mark, title, detail }: { mark: "ok" | "bad" | "open"; title: string; detail: string }) {
  const p = usePalette();
  const icon: IconName = mark === "ok" ? "checkC" : mark === "bad" ? "xC" : "clock";
  return (
    <View style={{ flexDirection: "row", alignItems: "flex-start", gap: 10 }} accessibilityLabel={`${title}: ${detail}`}>
      <View style={{ marginTop: 1 }}><Icon name={icon} size={20} color={mark === "ok" ? p.ok : mark === "bad" ? p.bad : p.muted} /></View>
      <View style={{ flex: 1 }}>
        <Text style={{ fontFamily: F.r, fontSize: 15, color: p.ink }}>{title}</Text>
        <Text style={{ fontFamily: F.r, fontSize: 12.5, color: p.muted }}>{detail}</Text>
      </View>
    </View>
  );
}

/** .kv inside a card: label muted on the left, value ink on the right (one line, cut when long). */
