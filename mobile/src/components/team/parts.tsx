/** .leader: the rank (gold for the first), the person's initials, name and figure, a muted line with one chip, and the bar. */
export function LeaderRow({ rank, name, figure, meta, chip, pct, onPress }: { rank: number; name: string; figure: string; meta: string; chip?: ReactNode; pct: number; onPress?: () => void }) {
  const p = usePalette();
  const lead = rank === 1;
  const body = (
    <View style={{ flexDirection: "row", alignItems: "center", gap: 12, paddingVertical: 10, paddingHorizontal: 16 }}>
      <Text style={{ width: 22, textAlign: "center", fontFamily: F.mono, fontSize: 14, color: lead ? p.goldInk : p.muted }}>{rank}</Text>
      <Avatar initials={initialsOf(name)} size={26} />
      <View style={{ flex: 1, minWidth: 0 }}>
        <View style={{ flexDirection: "row", alignItems: "center", justifyContent: "space-between", gap: 10 }}>
          <Text numberOfLines={1} style={{ flexShrink: 1, fontFamily: F.m, fontSize: 16, color: p.ink }}>{name}</Text>
          <Text style={{ fontFamily: F.r, fontSize: 16, color: p.ink, fontVariant: ["tabular-nums"] }}>{figure}</Text>
        </View>
        <View style={{ flexDirection: "row", alignItems: "center", justifyContent: "space-between", gap: 10, marginTop: 2, minHeight: 18 }}>
          <Text numberOfLines={1} style={{ flexShrink: 1, fontFamily: F.r, fontSize: 12.5, color: p.muted }}>{meta}</Text>
          {chip}
        </View>
        <Progress pct={pct} gold={lead} style={{ marginTop: 6 }} />
      </View>
    </View>
  );
  if (!onPress) return body;
  return <Pressable accessibilityRole="button" accessibilityLabel={`${name}, ${figure}`} onPress={onPress} android_ripple={{ color: p.surf2 }}>{body}</Pressable>;
}

function initialsOf(name: string): string {
  const parts = name.trim().split(/\s+/).filter(Boolean);
  return ((parts[0]?.[0] ?? "?") + (parts.length > 1 ? parts[parts.length - 1][0] : "")).toUpperCase();
}

/** Board I3 · a report as a card: its name and a chevron, what the number is, the number, its change, and a sparkline. */
export function ReportCard({ title, label, value, change, spark, onPress, testID }: { title: string; label: string; value: string; change?: ReactNode; spark?: number[]; onPress: () => void; testID?: string }) {
  const p = usePalette();
  return (
    <Card onPress={onPress}>
      <View testID={testID} accessibilityLabel={`${title}: ${value}`}>
        <View style={{ flexDirection: "row", alignItems: "center", justifyContent: "space-between" }}>
          <Text style={{ fontFamily: F.s, fontSize: 16, color: p.ink }}>{title}</Text>
          <Icon name="chevR" size={18} color={p.faint} />
        </View>
        <View style={{ flexDirection: "row", alignItems: "flex-end", justifyContent: "space-between", marginTop: 6, gap: 10 }}>
          <View style={{ flexShrink: 1 }}>
            <Text style={{ fontFamily: F.r, fontSize: 12.5, color: p.muted }}>{label}</Text>
            <Text numberOfLines={1} style={{ fontFamily: F.db, fontSize: 28, lineHeight: 31, letterSpacing: -0.8, color: p.ink, fontVariant: ["tabular-nums"] }}>{value}</Text>
            {change ?? null}
          </View>
          {spark && spark.length > 1 ? <Spark values={spark} /> : null}
        </View>
      </View>
    </Card>
  );
}

