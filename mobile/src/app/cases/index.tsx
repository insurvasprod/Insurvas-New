import { useState } from "react";
import { View } from "react-native";
import { router, useLocalSearchParams } from "expo-router";

import { CaseRows } from "@/components/cases/parts";
import { matches, pendingTabs, type ApplicationsAnswer, type PendingAnswer } from "@/components/cases/model";
import { Empty, Failed, Header, IOS, Loading, Screen, SearchBox, SectionHead, Segments } from "@/components/ui";
import { useSession } from "@/lib/session";
import { useLoad } from "@/lib/use-load";

/**
 * Board E5 · Pending cases: everything between submitted and issued. What needs you first (open
 * requirements someone other than the carrier must answer, and counteroffers), then what sits at the
 * carrier, then what issued this month. The Home tile "Cases need a doc" opens this on Needs you.
 * Data: GET /api/app/pending and GET /api/app/applications, the web's Applications › Waiting lists.
 */
type TabKey = "needs" | "carrier" | "issued";
const TABS: TabKey[] = ["needs", "carrier", "issued"];

export default function PendingCases() {
  const { api } = useSession();
  const params = useLocalSearchParams<{ tab?: string }>();
  const [tab, setTab] = useState<TabKey>(() => TABS.find((t) => t === params.tab) ?? "needs");
  const [searching, setSearching] = useState(false);
  const [query, setQuery] = useState("");
  const load = useLoad(async () => {
    const [pending, apps] = await Promise.all([api<PendingAnswer>("/api/app/pending"), api<ApplicationsAnswer>("/api/app/applications")]);
    return pendingTabs(pending, apps.applications);
  }, []);
  const data = load.data;
  const pick = (rows: NonNullable<typeof data>["needsYou"]) => rows.filter((r) => matches(r, query));
  // `as never`: the typed-routes list is regenerated by Metro, so a new route is unknown to it until then.
  const open = (caseId: string, requirementId?: string) => router.push({ pathname: "/cases/[caseId]", params: requirementId ? { caseId, requirement: requirementId } : { caseId } } as never);

  const items = [
    { key: "needs", label: "Needs you", count: data?.needsYou.length },
    { key: "carrier", label: "At carrier", count: data?.atCarrier.length },
    { key: "issued", label: "Issued", count: data?.issued.length },
  ];
  const tabs = <Segments items={items} value={tab} onChange={(k) => setTab(k as TabKey)} />;
  const header = (
    <Header title="Pending cases" back="Menu" onBack={() => router.back()} large
      actions={[{ icon: searching ? "x" : "search", label: searching ? "Close search" : "Search cases", onPress: () => { setSearching(!searching); setQuery(""); } }]}
      belowFull={<>
        {searching ? <View style={{ paddingHorizontal: 16, paddingBottom: 10 }}><SearchBox testID="cases-search" value={query} onChangeText={setQuery} placeholder="Search by client or carrier" autoFocus /></View> : null}
        {IOS ? <View style={{ paddingHorizontal: 16, paddingBottom: 10 }}>{tabs}</View> : tabs}
      </>} />
  );

  let body;
  if (!data && load.loading) body = <Loading rows={6} />;
  else if (!data) body = <Failed what="pending cases" message={load.error ?? "Something went wrong."} onRetry={load.reload} />;
  else if (tab === "needs") {
    const needs = pick(data.needsYou);
    const carrier = pick(data.atCarrier);
    body = (
      <>
        {needs.length ? <CaseRows rows={needs} onOpen={open} /> : <Empty icon="checkC" title={query ? "No match" : "Nothing needs you"} body={query ? undefined : "When a carrier asks for something only you or the client can give, it shows here first."} />}
        {carrier.length ? <><SectionHead>Moving at the carrier</SectionHead><CaseRows rows={carrier} onOpen={open} /></> : null}
      </>
    );
  } else {
    const rows = pick(tab === "carrier" ? data.atCarrier : data.issued);
    body = rows.length ? <CaseRows rows={rows} onOpen={open} />
      : <Empty icon={tab === "carrier" ? "hourglass" : "checkC"} title={query ? "No match" : tab === "carrier" ? "Nothing at the carrier" : "Nothing issued yet this month"} />;
  }

  return <Screen header={header} onRefresh={load.refresh} refreshing={load.refreshing}>{body}</Screen>;
}
